# Crear un arreglo (lista) con números enteros
numeros = [10, 20, 30, 40, 50]

# Acceder a un elemento por su índice (empieza en 0)
print(numeros[0])  # Salida: 10

# Modificar un elemento
numeros[1] = 25
print(numeros)  # Salida: [10, 25, 30, 40, 50]

# Agregar un nuevo elemento al final
numeros.append(60)
print(numeros)  # Salida: [10, 25, 30, 40, 50, 60]
